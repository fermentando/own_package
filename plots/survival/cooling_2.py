    def _Lambda(self, T):
        if np.isnan(T):
            return np.nan


        # converstion to code units given line 1239
        sdT_conv = np.array(self.sdT) * self.sdT_fac


        # given line 1272
        sdL_conv = self.sdL_fac * np.array(self.sdL)


        i = np.arange(len(self.sdT))[T >= sdT_conv][-1]
        r = sdL_conv[i] * (T / sdT_conv[i])**self.sdexpt[i]

        return r


    def Lambda(self, T):
        """given T in code units return Lambda in code units"""
        r = np.vectorize(self._Lambda)(T / self.conv['T'])
        return r * self.conv['Lambda']


    def tcool(self, T, dens = 1000.):
        """given T in code units returns cooling time in code units"""
        mu_e = 1.17
        gamma = 5/3.
        if self.units == 'physical':
            kB = 1.38e-16
        else:
            kB = 1.
        if self.tcool_fac is None:
            return mu_e**2 * T * kB / ((gamma - 1 ) * dens * self.Lambda(T))
        else:
            return self.tcool_fac * T * self.sdT_fac / (dens * self.Lambda(T))


